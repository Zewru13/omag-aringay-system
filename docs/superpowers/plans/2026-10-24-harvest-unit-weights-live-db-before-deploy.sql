-- Harvest unit weights: live-database change for Django migrations production.0062_harvest_unit_weights and
-- production.0063_seed_harvest_unit_weights.
--
-- PROJECT: omag-aringay (ref zqvemhtzrccbofvwneph). Do NOT run on zewru_db (the old copy).
-- RUN THIS BEFORE the new backend is deployed (it reads these columns on every harvest query). It is only additions: nothing is
-- dropped and no existing row changes, so the old backend keeps working while it is in place. There is no "step 2".
-- Safe to run more than once.
--
-- What it does:
--   * creates the table production_harvestunitweight (Settings > Harvest Unit Settings: how many kg one harvest unit weighs, for every
--     crop or for one crop) and locks it down like every other table in public (row level security on, as in
--     2026-10-20-lock-down-public-schema.sql);
--   * gives it its five starting rows: Metric Ton 1000, Cavan (50kg) 50, cavan 50, bags 50 (all for every crop; official or the form's
--     own label, with the source in the note) and Sack 50 for Corn (Mais) (marked as not an official standard);
--   * adds two columns to production_harvestrecord, both empty for every harvest that already exists: quantity_harvested (what was
--     counted, e.g. 20 sacks) and kg_per_unit (the weight that was used). volume_kg of every existing harvest is NOT touched;
--   * records migrations 0062 and 0063 so Django does not run them again.

-- 0. BEFORE (read-only): the table and the two columns should not exist yet (no rows), and how many harvests there are.
select table_name from information_schema.tables where table_schema = 'public' and table_name = 'production_harvestunitweight';
select column_name from information_schema.columns
 where table_schema = 'public' and table_name = 'production_harvestrecord' and column_name in ('quantity_harvested', 'kg_per_unit');
select count(*) as harvests from production_harvestrecord;

-- 1. THE CHANGE (one transaction: all or nothing)
begin;

create table if not exists public.production_harvestunitweight (
    id          bigint generated by default as identity primary key,
    unit        varchar(40) not null,
    kg_per_unit numeric(10,4) null,
    note        varchar(200) not null default '',
    crop_type_id bigint null references public.production_croptype (id) on delete cascade deferrable initially deferred
);
create index if not exists production_harvestunitweight_crop_type_id_idx on public.production_harvestunitweight (crop_type_id);
alter table public.production_harvestunitweight enable row level security;

alter table public.production_harvestrecord add column if not exists quantity_harvested numeric(12,2) null;
alter table public.production_harvestrecord add column if not exists kg_per_unit numeric(10,4) null;

insert into public.production_harvestunitweight (unit, kg_per_unit, note, crop_type_id)
select v.unit, v.kg, v.note, null
  from (values
    ('Metric Ton',   1000, 'Official: 1 metric ton = 1,000 kg.'),
    ('Cavan (50kg)', 50,   'Official: NFA Letter-Circular AO-2013-04-003, one cavan of rice or corn is 50 kg net.'),
    ('cavan',        50,   'Official: NFA Letter-Circular AO-2013-04-003, one cavan of rice or corn is 50 kg net.'),
    ('bags',         50,   'The 50 kg bag the harvest form has always labelled "Bags (50 kg/bag)".')
  ) as v(unit, kg, note)
 where not exists (select 1 from public.production_harvestunitweight w where lower(w.unit) = lower(v.unit) and w.crop_type_id is null);

insert into public.production_harvestunitweight (unit, kg_per_unit, note, crop_type_id)
select 'Sack', 50, 'Not an official standard: a sack of corn trades as one 50 kg cavan (NFA).', c.id
  from public.production_croptype c
 where c.name = 'Corn (Mais)'
   and not exists (select 1 from public.production_harvestunitweight w where lower(w.unit) = 'sack' and w.crop_type_id = c.id);

insert into public.django_migrations (app, name, applied)
select v.app, v.name, now()
  from (values ('production', '0062_harvest_unit_weights'), ('production', '0063_seed_harvest_unit_weights')) as v(app, name)
 where not exists (select 1 from public.django_migrations m where m.app = v.app and m.name = v.name);

commit;

-- 2. AFTER (read-only): one row for the table, two for the columns; the five starting rows; every existing harvest still has no
-- quantity (counted = 0) and its volume_kg as it was; two migration rows.
select table_name from information_schema.tables where table_schema = 'public' and table_name = 'production_harvestunitweight';
select column_name from information_schema.columns
 where table_schema = 'public' and table_name = 'production_harvestrecord' and column_name in ('quantity_harvested', 'kg_per_unit');
select w.unit, c.name as crop, w.kg_per_unit from production_harvestunitweight w left join production_croptype c on c.id = w.crop_type_id order by w.unit;
select count(*) filter (where quantity_harvested is not null) as counted, count(*) as harvests from production_harvestrecord;
select app, name from django_migrations where app = 'production' and name in ('0062_harvest_unit_weights', '0063_seed_harvest_unit_weights');
