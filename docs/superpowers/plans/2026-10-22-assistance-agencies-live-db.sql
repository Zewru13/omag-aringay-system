-- Run on the Supabase project "omag-aringay" (ref zqvemhtzrccbofvwneph) BEFORE the new backend is deployed.
-- Adds the managed list of assistance source agencies (interventions migration 0020) and its five starting rows.
-- Safe to run twice.

create table if not exists public.interventions_assistanceagency (
    id        bigint generated by default as identity primary key,
    name      varchar(150) not null unique,
    is_active boolean      not null default true
);

-- Same lock-down as every other table in public (see 2026-10-20-lock-down-public-schema.sql).
alter table public.interventions_assistanceagency enable row level security;

insert into public.interventions_assistanceagency (name, is_active) values
    ('LGU - Aringay', true),
    ('Office of the Provincial Agriculturist', true),
    ('Department of Agriculture (DA)', true),
    ('Department of Agrarian Reform (DAR)', true),
    ('Non-Government Organization (NGO)', true)
on conflict (name) do nothing;

-- Tell Django this migration is applied.
insert into public.django_migrations (app, name, applied)
select 'interventions', '0020_assistance_agencies', now()
where not exists (select 1 from public.django_migrations where app = 'interventions' and name = '0020_assistance_agencies');
