-- What it does:
--   * creates the managed list table farmers_parcelclassification (name unique, is_active) with its three starting rows - the
--     three tick-boxes every parcel form used to have: Organic Farm, Within Ancestral Domain, Agrarian Reform Beneficiary;
--   * locks the new table down like every other table in public (row level security on, as in
--     2026-10-20-lock-down-public-schema.sql);
--   * adds farmers_farmparcel.classifications (jsonb, the list of ticked names) and fills it from the old three tick-box
--     columns, so every parcel keeps what was ticked;
--   * gives the three old tick-box columns a default of false, so the new backend (which no longer writes them) can still
--     save parcels until step 2 drops them;
--   * records migration 0032 as applied.

-- 0. BEFORE (read-only)
select count(*) as parcels,
       count(*) filter (where is_organic) as organic,
       count(*) filter (where within_ancestral_domain) as ancestral_domain,
       count(*) filter (where is_agrarian_reform_beneficiary) as agrarian_reform
  from farmers_farmparcel;

-- 1. THE CHANGE (one transaction: all or nothing)
begin;

create table if not exists public.farmers_parcelclassification (
    id        bigint generated by default as identity primary key,
    name      varchar(150) not null unique,
    is_active boolean      not null default true
);
alter table public.farmers_parcelclassification enable row level security;

insert into public.farmers_parcelclassification (name, is_active) values
    ('Organic Farm', true), ('Within Ancestral Domain', true), ('Agrarian Reform Beneficiary', true)
on conflict (name) do nothing;

alter table public.farmers_farmparcel add column if not exists classifications jsonb not null default '[]'::jsonb;

update public.farmers_farmparcel
   set classifications =
         coalesce(case when is_organic then '["Organic Farm"]'::jsonb end, '[]'::jsonb)
      || coalesce(case when within_ancestral_domain then '["Within Ancestral Domain"]'::jsonb end, '[]'::jsonb)
      || coalesce(case when is_agrarian_reform_beneficiary then '["Agrarian Reform Beneficiary"]'::jsonb end, '[]'::jsonb)
 where (is_organic or within_ancestral_domain or is_agrarian_reform_beneficiary) and classifications = '[]'::jsonb;

alter table public.farmers_farmparcel alter column is_organic set default false;
alter table public.farmers_farmparcel alter column within_ancestral_domain set default false;
alter table public.farmers_farmparcel alter column is_agrarian_reform_beneficiary set default false;

insert into public.django_migrations (app, name, applied)
select 'farmers', '0032_parcel_classifications', now()
 where not exists (select 1 from public.django_migrations where app = 'farmers' and name = '0032_parcel_classifications');

commit;

-- 2. AFTER (read-only): the three starting rows; every parcel that had a tick has the same names in classifications.
select name, is_active from public.farmers_parcelclassification order by name;
select count(*) as parcels_with_classifications from farmers_farmparcel where classifications <> '[]'::jsonb;
select app, name from django_migrations where app = 'farmers' order by name desc limit 2;
